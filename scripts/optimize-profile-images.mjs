// Run with: node scripts/optimize-profile-images.mjs (requires ffmpeg and ffprobe).
// Only generates derivatives: the original photographs are never modified.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(root, "src/assets/profiles");
mkdirSync(output, { recursive: true });
const files = ["diputadosData.jsx", "representantes.jsx"];
const names = [...new Set(files.flatMap((file) =>
  [...readFileSync(resolve(root, "src/data", file), "utf8")
    .matchAll(/from\s+["']\.\.\/assets\/([^"']+)\.webp["']/g)].map((match) => match[1]),
))];
const imports = [];
const entries = [];
let originalBytes = 0;
let cardBytes = 0;

function dimensions(file) {
  return JSON.parse(execFileSync("ffprobe", ["-v", "error", "-select_streams", "v:0",
    "-show_entries", "stream=width,height", "-of", "json", file], { encoding: "utf8" })).streams[0];
}

for (const [index, name] of names.entries()) {
  const original = resolve(root, `src/assets/${name}.webp`);
  const { width, height } = dimensions(original);
  const bytes = statSync(original).size;
  originalBytes += bytes;
  const originalId = `original${index}`;
  imports.push(`import ${originalId} from "../assets/${name}.webp";`);

  function derivative(label, targetWidth, targetHeight) {
    const filename = `${name}-${label}.webp`;
    const destination = resolve(output, filename);
    execFileSync("ffmpeg", ["-hide_banner", "-loglevel", "error", "-y", "-i", original,
      "-vf", `scale=${targetWidth}:${targetHeight}:flags=lanczos`, "-frames:v", "1",
      "-c:v", "libwebp", "-quality", "84", "-compression_level", "6", destination]);
    const id = `${label}${index}`;
    imports.push(`import ${id} from "../assets/profiles/${filename}";`);
    return { id, width: targetWidth, height: targetHeight, bytes: statSync(destination).size };
  }

  const originalInfo = { id: originalId, width, height, bytes };
  const cardWidth = Math.min(width, 960);
  const needsCard = width > 960 || bytes > 180_000;
  const card = needsCard
    ? derivative("card", cardWidth, Math.round(height * cardWidth / width))
    : originalInfo;
  const small = card.width > 480 && card.bytes > 45_000
    ? derivative("small", 480, Math.round(height * 480 / width))
    : card;
  // Large portraits are requested only when their profile is opened.
  const modalScale = Math.min(1, 1600 / Math.max(width, height));
  const modalWidth = Math.round(width * modalScale);
  const modal = modalWidth <= card.width ? card : needsCard
    ? derivative("modal", modalWidth, Math.round(height * modalScale))
    : originalInfo;
  const srcSet = small.id === card.id ? "undefined"
    : "`${" + small.id + "} " + small.width + "w, ${" + card.id + "} " + card.width + "w`";
  entries.push(`  [${originalId}]: { card: ${card.id}, srcSet: ${srcSet}, modal: ${modal.id}, width: ${card.width}, height: ${card.height} },`);
  cardBytes += card.bytes;
  console.log(`${name}: ${Math.round(bytes / 1024)} KB -> card ${Math.round(card.bytes / 1024)} KB (${card.width}x${card.height})`);
}

writeFileSync(resolve(root, "src/data/profileImages.js"),
  "// Generated by scripts/optimize-profile-images.mjs. Do not edit by hand.\n" +
  imports.join("\n") + "\n\nexport const profileImages = {\n" + entries.join("\n") + "\n};\n");
console.log(`All portraits: ${originalBytes} -> ${cardBytes} bytes at the largest card size.`);
